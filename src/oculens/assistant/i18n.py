_TR_FILE = __import__("pathlib").Path(__file__).with_name("translations.json")
_TR_CACHE: dict | None = None


def _table() -> dict:
    global _TR_CACHE
    if _TR_CACHE is None:
        import json
        _TR_CACHE = json.loads(_TR_FILE.read_text(encoding="utf-8")) if _TR_FILE.exists() else {}
    return _TR_CACHE


def tr_static(text: str, lang: str) -> str | None:
    """Translation of a fixed English text, line by line (list markers kept). None if any line is missing."""
    if lang == "en" or not text:
        return text
    table = _table().get(lang, {})
    out = []
    for line in text.split("\n"):
        body = line.strip()
        if not body:
            out.append(line)
            continue
        bullet = ""
        if body.startswith("- "):
            bullet, body = "- ", body[2:]
        t = LABELS.get(body, {}).get(lang) or table.get(body)
        if t is None:
            return None
        out.append(bullet + t)
    return "\n".join(out)


def tr_or_en(text: str, lang: str) -> str:
    """For interface text: the translation when there is one, else the English."""
    return tr_static(text, lang) or text
