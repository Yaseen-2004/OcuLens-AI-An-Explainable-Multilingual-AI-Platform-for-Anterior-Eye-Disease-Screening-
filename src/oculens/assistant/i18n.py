def tr(key: str, lang: str = "en", **kw) -> str:
    row = T[key]
    return row.get(lang if lang in row else "en", row["en"]).format(**kw)


def to_english_keywords(text: str) -> str:
    """English keywords for words written in Indian scripts (empty when there are none)."""
    found = [en for en, words in KEYWORDS.items() if any(w in (text or "") for w in words)]
    return " ".join(found)


def part_of_day(now: _dt.datetime | None = None) -> str:
    h = (now or _dt.datetime.now()).hour
    return "morning" if h < 12 else ("afternoon" if h < 17 else "evening")


def welcome_text(user: dict, stats: dict, lang: str = "en", now: _dt.datetime | None = None) -> str:
    """Spoken greeting after login, with live numbers from the portal."""
    greet = tr(part_of_day(now), lang)
    name = user.get("name") or user.get("username") or ""
    pending = int(stats.get("pending", 0) or 0)
    if user.get("role") == "patient":
        st = stats.get("patient_status") or "none"
        return tr("welcome_patient", lang, greet=greet, name=name.split(" ")[0], status=tr(f"pstatus_{st}", lang))
    if user.get("role") == "admin":
        return tr("welcome_admin", lang, greet=greet, name=name, patients=stats.get("patients", 0),
                  cases=stats.get("cases", 0), pending=pending)
    pending_line = tr("pending_some", lang, pending=pending) if pending else tr("pending_none", lang)
    return tr("welcome_doctor", lang, greet=greet, name=name, pending_line=pending_line,
              referred=stats.get("referred", 0))



